// Package setup implements `agentgw init`: discovery, starter files, keys and
// Claude Code registration. It owns no globals and never touches os.Stdin or
// os.Stdout; callers pass the streams.
package setup

import (
	"context"
	"fmt"
	"os/exec"
	"regexp"
	"strings"
	"time"
	"unicode"

	"github.com/modelcontextprotocol/go-sdk/mcp"
)

// Discover starts command as an MCP server, lists its tools and shuts it down.
// The whole call is bounded by 20 s; the process is killed 5 s after close.
func Discover(ctx context.Context, command []string) ([]string, error) {
	if len(command) == 0 {
		return nil, fmt.Errorf("no command")
	}
	ctx, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	cmd := exec.Command(command[0], command[1:]...)
	client := mcp.NewClient(&mcp.Implementation{Name: "agentgw-init", Version: "v0"}, nil)
	sess, err := client.Connect(ctx, &mcp.CommandTransport{Command: cmd, TerminateDuration: 5 * time.Second}, nil)
	if err != nil {
		return nil, err
	}
	var names []string
	var cursor string
	for {
		res, err := sess.ListTools(ctx, &mcp.ListToolsParams{Cursor: cursor})
		if err != nil {
			sess.Close()
			return nil, err
		}
		for _, t := range res.Tools {
			names = append(names, t.Name)
		}
		if cursor = res.NextCursor; cursor == "" {
			break
		}
	}
	return names, sess.Close()
}

var destructive = map[string]bool{}

func init() {
	for _, v := range strings.Fields("delete remove drop destroy purge truncate kill pay refund transfer send publish deploy") {
		destructive[v] = true
	}
}

// words splits on _ - . and camelCase boundaries, lower-cased.
func words(s string) []string {
	var out []string
	var cur []rune
	flush := func() {
		if len(cur) > 0 {
			out = append(out, strings.ToLower(string(cur)))
			cur = nil
		}
	}
	r := []rune(s)
	for i, c := range r {
		if c == '_' || c == '-' || c == '.' {
			flush()
			continue
		}
		if unicode.IsUpper(c) && len(cur) > 0 &&
			(unicode.IsLower(r[i-1]) || (i+1 < len(r) && unicode.IsLower(r[i+1]))) {
			flush()
		}
		cur = append(cur, c)
	}
	flush()
	return out
}

func isDestructive(tool string) bool {
	for _, w := range words(tool) {
		if destructive[w] {
			return true
		}
	}
	return false
}

// safeName keeps tool names that cannot break out of a YAML comment or string.
var safeName = regexp.MustCompile(`^[A-Za-z0-9_.:-]+$`)

// StarterPolicy renders policy.yaml. When discovered is false the tools are
// ignored and the template is written.
func StarterPolicy(server string, tools []string, discovered bool, now time.Time) []byte {
	var safe, flagged []string
	if discovered {
		for _, t := range tools {
			if !safeName.MatchString(t) {
				continue // shortcut: odd names are left out of the starter file, add them by hand
			}
			safe = append(safe, server+"."+t)
			if isDestructive(t) {
				flagged = append(flagged, server+"."+t)
			}
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by agentgw init on %s for upstream %q.\n", now.Format("2006-01-02"), server)
	if !discovered {
		b.WriteString("# Tools: not listed (server did not start)\n")
	} else {
		list := safe
		if len(list) > 10 {
			list = append(append([]string(nil), list[:10]...), "...")
		}
		fmt.Fprintf(&b, "# Tools found: %s\n", strings.Join(list, ", "))
	}
	b.WriteString("# Grammar: contracts/policy-yaml.md. Changes apply on the next tool call.\nversion: \"1\"\nrules:\n")
	b.WriteString("  # Tools whose names suggest a destructive or paid action wait for a human\n")
	b.WriteString("  # in `agentgw watch`. Edit the list; add tools here to require approval.\n")
	pre, quoted := "  ", flagged
	if len(flagged) == 0 {
		pre = "  # "
		ex := server + ".*"
		if len(safe) > 0 {
			ex = safe[0]
		}
		quoted = []string{ex}
	}
	for i, t := range quoted {
		quoted[i] = `"` + t + `"`
	}
	fmt.Fprintf(&b, "%s- id: review-destructive\n%s  effect: require_approval\n%s  tools: [%s]\n%s  timeout: 5m\n",
		pre, pre, pre, strings.Join(quoted, ", "), pre)
	b.WriteString("  - id: allow-all\n    effect: allow\n    tools: [\"*\"]\n")
	return []byte(b.String())
}

// StarterConfig renders agentgw.yaml (contracts/schemas/config.schema.json).
func StarterConfig(name string, command []string, agent, owner string) []byte {
	q := func(s string) string { return fmt.Sprintf("%q", s) }
	var cmd []string
	for _, c := range command {
		cmd = append(cmd, q(c))
	}
	return []byte(fmt.Sprintf(`# agentgw gateway config. Schema: contracts/schemas/config.schema.json
version: "1"
agent:
  id: %s
  owner: %s
currency: USD
listen: ""
upstreams:
  - name: %s
    command: [%s]
policy_path: policy.yaml
prices: []
redaction:
  fields: [api_key, authorization, password, secret, token]
  patterns: []
approvals:
  cli:
    token_path: approver.key
ledger:
  path: ledger.jsonl
  checkpoint_every: 100
key_path: ledger.key
state_path: agentgw.db
`, q(agent), q(owner), q(name), strings.Join(cmd, ", ")))
}
